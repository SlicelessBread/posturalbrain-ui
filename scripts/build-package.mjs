// Generates the files the package ships that are derived from the design-system sources:
// styles.css (token variables for both themes + component styles), the icon table and
// the theme colours the theme script needs. `npm test` checks that they are up to date.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { compileTokensCss } from './tokens-css.mjs';
import { loadIcon } from './build-previews.mjs';

const PROJECT = 'design-system/project';
const ICONS = path.join(PROJECT, 'assets/Icone');
const HEADER = '// Generated by scripts/build-package.mjs. Do not edit: run `npm run build:package`.\n';

export function buildPackageFiles() {
  const tokens = JSON.parse(fs.readFileSync(path.join(PROJECT, 'tokens.json'), 'utf8'));
  const bundle = fs.readFileSync(path.join(PROJECT, 'components/bundle.css'), 'utf8');

  const names = fs.readdirSync(ICONS).filter((f) => f.endsWith('.svg')).map((f) => path.basename(f, '.svg')).sort();
  const icons = `${HEADER}export const ICONS = {\n${names.map((n) => `  ${JSON.stringify(n)}: ${JSON.stringify(loadIcon(n))},`).join('\n')}\n} as const;\n\nexport type IconName = keyof typeof ICONS;\n`;

  const ground = tokens.color.tokens.find((t) => t.name === 'bg-0');
  const first = tokens.color.themes[0].id;
  const colors = Object.fromEntries(tokens.color.themes.map((theme) => [theme.id, typeof ground.value === 'string' ? ground.value : (ground.value[theme.id] ?? ground.value[first])]));
  const themeColors = `${HEADER}/** The deepest ground colour of each theme, for <meta name="theme-color">. */\nexport const THEME_COLORS = ${JSON.stringify(colors, null, 2)} as const;\n`;

  return {
    'styles.css': `${compileTokensCss(tokens, tokens.name ?? 'POSTURALBRAIN')}\n${bundle}`,
    'src/icons.generated.ts': icons,
    'src/theme/colors.generated.ts': themeColors,
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [file, text] of Object.entries(buildPackageFiles())) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, text);
    console.log(`wrote ${file}`);
  }
}
